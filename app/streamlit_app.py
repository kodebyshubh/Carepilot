@st.cache_resource(show_spinner="Loading retrieval models (first run downloads ~200 MB)...")
def load_retriever() -> Retriever:
    retriever = Retriever.load()
    retriever.search("warm up", k=1)  # load embedder + cross-encoder once
    return retriever


@st.cache_resource(ttl=300)
def load_llm(provider: str):
    return get_llm(provider)


def sidebar() -> str:
    st.sidebar.title("🩺 CarePilot")
    st.sidebar.caption("Risk prediction + evidence-grounded explanations")
    choice = st.sidebar.selectbox(
        "Answer generator",
        PROVIDERS,
        index=PROVIDERS.index(default)
        if (default := get_settings().llm_provider) in PROVIDERS
        else 0,
        help="auto = Groq if GROQ_API_KEY is set, else local Ollama if running, else extractive.",
    )
    try:
        st.sidebar.success(f"Using: {load_llm(choice).label}")
    except LLMError as exc:
        st.sidebar.error(str(exc))
        choice = "extractive"
    st.sidebar.warning(DISCLAIMER)
    st.sidebar.markdown(
        "Data: Pima Indians Diabetes, UCI Cleveland Heart Disease. "
        "Documents: NIDDK, NHLBI (NIH), WHO. Models: scikit-learn, "
        "BAAI/bge-small-en-v1.5, ms-marco-MiniLM-L-6-v2 cross-encoder."
    )
    return choice


def show_red_flags(flags) -> None:
    for f in flags:
        st.error(f"**{f.category}.** {f.message} Emergency numbers: {EMERGENCY_NUMBERS}.")


def show_answer(ans: Answer) -> None:
    if ans.abstained:
        st.warning(ans.text)
        st.caption(f"Why: {ans.reason}")
        return
    st.markdown(ans.text)
    st.caption(f"Generated by {ans.provider}. Numbers in brackets refer to the sources below.")
    st.markdown("**Sources**")
    for s in ans.sources:
        where = f"{s.title} > {s.section}" if s.section else s.title
        with st.expander(f"[{s.n}] {s.publisher}: {where}"):
            st.markdown(f"[{s.url}]({s.url})  \nRelevance score: {s.score:.2f}")
            st.text(s.text)


# ---------- Risk tab ----------


def patient_form(spec: DiseaseSpec) -> dict[str, float | None] | None:
    preset_name = st.selectbox("Start from", list(PRESETS[spec.name]), key=f"preset_{spec.name}")
    preset = PRESETS[spec.name][preset_name]
    with st.form(key=f"form_{spec.name}"):
        cols = st.columns(3)
        values: dict[str, float | None] = {}
        for i, name in enumerate(spec.feature_order):
            info = spec.features[name]
            col = cols[i % 3]
            label = f"{info.label} ({info.unit})" if info.unit else info.label
            if info.choices:
                codes = list(info.choices)
                values[name] = col.selectbox(
                    label,
                    codes,
                    index=codes.index(int(preset.get(name, codes[0]))),
                    format_func=info.choices.get,
                    key=f"{spec.name}_{name}_{preset_name}",
                )
                continue
            if name in OPTIONAL_FIELDS and col.checkbox(
                f"{info.label}: not measured",
                value=name not in preset,
                key=f"{spec.name}_{name}_na_{preset_name}",
            ):
                values[name] = None
                continue
            # Streamlit requires min, max, value and step to share one numeric type.
            num = int if info.unit in ("count", "years", "bpm", "mg/dL", "mm Hg") else float
            default = preset.get(name, (info.min_value + info.max_value) / 2)
            values[name] = col.number_input(
                label, min_value=num(info.min_value), max_value=num(info.max_value),
                value=num(default), step=num(1 if num is int else 0.1),
                help=info.help or None, key=f"{spec.name}_{name}_{preset_name}",
            )  # fmt: skip
        submitted = st.form_submit_button("Estimate risk", type="primary")
    return values if submitted else None


def factor_chart(result: RiskResult) -> alt.Chart:
    df = pd.DataFrame(
        [{"factor": f.label, "contribution": f.contribution, "effect": f"{f.direction} risk"}
         for f in result.factors[:8]]
    )  # fmt: skip
    return (
        alt.Chart(df)
        .mark_bar()
        .encode(
            x=alt.X("contribution:Q", title="Contribution to risk (SHAP, log-odds)"),
            y=alt.Y("factor:N", sort="-x", title=None, axis=alt.Axis(labelLimit=260)),
            color=alt.Color(
                "effect:N",
                scale=alt.Scale(
                    domain=["raises risk", "lowers risk"], range=["#d62728", "#2ca02c"]
                ),
            ),
            tooltip=["factor", alt.Tooltip("contribution:Q", format=".2f")],
        )
        .properties(height=260)
    )


def show_risk(result: RiskResult) -> None:
    c1, c2, c3 = st.columns(3)
    c1.metric("Estimated risk", f"{result.probability:.0%}")
    c2.markdown(f"**Risk band**  \n:{BAND_COLOR[result.band]}[**{result.band}**]")
    c3.metric("Screening threshold", f"{result.threshold:.0%}",
              help="Chosen for at least 85% sensitivity on training data.")  # fmt: skip
    st.caption(
        f"Model: {result.model}. "
        + (f"Not provided, imputed with training medians: {', '.join(result.imputed)}. "
           if result.imputed else "")
        + "A population-level estimate from a small research dataset, not a diagnosis."
    )  # fmt: skip
    st.altair_chart(factor_chart(result), width="stretch")


def risk_tab(provider: str) -> None:
    disease = st.radio("Condition", list(DISEASE_LABELS), format_func=DISEASE_LABELS.get,
                       horizontal=True)  # fmt: skip
    spec = SPECS[disease]
    values = patient_form(spec)
    if values is not None:
        try:
            st.session_state["risk"] = (predict_risk(disease, values), values)
        except PatientValidationError as exc:
            for err in exc.errors:
                st.error(err)
            return
        st.session_state.pop("explanation", None)  # new patient: explanation is stale
    stored = st.session_state.get("risk")
    if not stored or stored[0].disease != disease:
        return
    result, entered = stored
    show_red_flags(check_vitals(disease, entered))
    show_risk(result)
    show_what_if(spec, result, entered)
    st.subheader("Why, and what to do: explanation from the documents")
    if "explanation" not in st.session_state:  # Streamlit reruns on every click; compute once
        with st.spinner("Retrieving evidence and writing the explanation..."):
            st.session_state["explanation"] = explain_risk(
                result, load_retriever(), load_llm(provider)
            )
    show_answer(st.session_state["explanation"])


def show_what_if(spec: DiseaseSpec, result: RiskResult, entered: dict) -> None:
    """Sliders for factors a person can change; the estimate updates live."""
    st.subheader("What if?")
    st.caption(
        "Move a factor a person can influence and see how the model's estimate responds. "
        "This reflects patterns in the training data, not a guaranteed effect of treatment."
    )
    factors = [f for f in MODIFIABLE[spec.name] if entered.get(f) is not None]
    cols = st.columns(len(factors) + 1)
    changes = {}
    for col, name in zip(cols, factors, strict=False):
        info = spec.features[name]
        value = float(entered[name])
        changes[name] = col.slider(
            f"{info.label} ({info.unit})",
            min_value=float(info.min_value),
            max_value=float(info.max_value),
            value=value,
            step=1.0 if info.max_value > 50 else 0.1,
            key=f"whatif_{spec.name}_{name}_{value}",  # new patient value resets the slider
        )
    simulated = what_if(spec.name, entered, changes)
    delta = simulated.probability - result.probability
    cols[-1].metric(
        "Simulated risk",
        f"{simulated.probability:.0%}",
        delta=f"{delta:+.0%}" if abs(delta) >= 0.005 else None,
        delta_color="inverse",  # lower risk shown in green
    )


# ---------- Ask tab ----------


def ask_tab(provider: str) -> None:
    st.markdown("Ask a health question. Answers use only the indexed public documents.")
    cols = st.columns(len(EXAMPLE_QUESTIONS))
    example_clicked = False
    for col, q in zip(cols, EXAMPLE_QUESTIONS, strict=True):
        if col.button(q, width="stretch"):
            st.session_state["question"] = q  # set before the text_input is created
            example_clicked = True
    question = st.text_input("Your question", key="question", max_chars=500)
    if st.button("Ask", type="primary") or example_clicked:
        if not question.strip():
            st.info("Type a question or pick an example.")
            return
        with st.spinner("Searching the documents..."):
            st.session_state["qa"] = answer_question(question, load_retriever(), load_llm(provider))
    ans: Answer | None = st.session_state.get("qa")
    if ans is None:
        return
    show_red_flags(check_red_flags(ans.question))
    show_answer(ans)
    show_xray(ans)


@st.cache_data(show_spinner=False, max_entries=64)
def pipeline_trace(question: str) -> pd.DataFrame:
    rows = load_retriever().trace(question)
    return pd.DataFrame(
        {
            "Passage": [r.passage for r in rows],
            "Dense rank": [r.dense_rank for r in rows],
            "BM25 rank": [r.bm25_rank for r in rows],
            "After fusion (RRF)": [r.rrf_rank for r in rows],
            "Final (reranked)": [r.rerank_rank for r in rows],
            "Reranker score": [round(r.rerank_score, 2) for r in rows],
        }
    )


def show_xray(ans: Answer) -> None:
    """Make the retrieval pipeline visible: how each stage ranked the passages."""
    with st.expander("Pipeline X-ray: how this answer was found"):
        threshold = load_abstain_threshold()
        top = ans.top_score
        if top is None:
            st.markdown("No passages retrieved.")
            return
        verdict = (
            "passed, so the LLM was asked"
            if top >= threshold
            else "failed, so the app abstained without calling the LLM"
        )
        st.markdown(
            "1. **BM25** (keywords) and **dense search** (bge-small embeddings in FAISS) each "
            "return their top 20 passages.\n"
            "2. **Reciprocal Rank Fusion** merges the two rankings.\n"
            "3. A **cross-encoder reranker** reads question and passage together and re-scores "
            "the top 20.\n"
            f"4. **Relevance gate:** best reranker score {top:.2f} vs threshold "
            f"{threshold:.2f}: {verdict}."
        )
        st.dataframe(pipeline_trace(ans.question), hide_index=True, width="stretch")
        st.caption("Empty rank = that stage did not place the passage in its top 20.")


# ---------- Report tab ----------


def metrics_frame(comparison: dict, key: str) -> pd.DataFrame:
    rows = {}
    for model, c in comparison.items():
        rows[model] = {
            m: f"{v['value']:.3f} [{v['ci_low']:.2f}, {v['ci_high']:.2f}]"
            for m, v in c[key].items()
        }
    return pd.DataFrame(rows)


def report_tab() -> None:
    for disease, label in DISEASE_LABELS.items():
        d = MODELS_DIR / disease
        if not (d / "metadata.json").exists():
            st.info(f"No trained {label} model yet.")
            continue
        meta = json.loads((d / "metadata.json").read_text(encoding="utf-8"))
        comp = json.loads((d / "metrics.json").read_text(encoding="utf-8"))
        st.subheader(f"{label}: {meta['selected_model']} selected")
        st.write(meta["selection_reason"])
        st.markdown(f"Held-out test set at tuned threshold **{meta['threshold']:.2f}** "
                    "(value [95% bootstrap CI]):")  # fmt: skip
        st.dataframe(metrics_frame(comp, "test_at_tuned"), width="stretch")
        cols = st.columns(3)
        for col, img in zip(cols, ("roc.png", "calibration.png", "confusion.png"), strict=True):
            col.image(str(d / img))
    rag = REPORTS_DIR / "rag_eval.md"
    if rag.exists():
        st.divider()
        st.markdown(rag.read_text(encoding="utf-8"))


def main() -> None:
    provider = sidebar()
    st.title("CarePilot")
    st.caption(
        "Diabetes and heart-disease risk estimates, explained with cited public-health documents."
    )
    tabs = st.tabs(["Risk assessment", "Ask the documents", "Model & RAG report"])
    with tabs[0]:
        risk_tab(provider)
    with tabs[1]:
        ask_tab(provider)
    with tabs[2]:
        report_tab()


main()
