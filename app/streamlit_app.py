"""CarePilot Streamlit interface.

Run: uv run streamlit run app/streamlit_app.py
Tabs: Risk assessment (ML + personalized cited explanation), Ask the documents (RAG Q&A),
Model & RAG report (metrics). Patient data lives only in the browser session; nothing is
written to disk or logged.
"""

