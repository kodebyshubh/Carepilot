"""Render reports/ml_report.md from saved model artifacts (models/<disease>/*.json)."""

from __future__ import annotations

import json
from pathlib import Path

from carepilot.config import MODELS_DIR, REPORTS_DIR

ROWS = (
    ("accuracy", "Accuracy"),
    ("precision", "Precision"),
    ("recall", "Recall"),
    ("f1", "F1"),
    ("roc_auc", "ROC-AUC"),
    ("brier", "Brier (lower better)"),
)


def _cell(m: dict[str, float]) -> str:
    return f"{m['value']:.3f} [{m['ci_low']:.2f}, {m['ci_high']:.2f}]"


def metrics_table(comparison: dict, key: str) -> str:
    models = list(comparison)
    lines = ["| Metric | " + " | ".join(models) + " |", "|---|" + "---|" * len(models)]
    for k, label in ROWS:
        lines.append(
            f"| {label} | " + " | ".join(_cell(comparison[m][key][k]) for m in models) + " |"
        )
    return "\n".join(lines)


def cv_table(comparison: dict) -> str:
    lines = ["| Model | CV ROC-AUC (mean +/- sd, 5-fold) | Best params |", "|---|---|---|"]
    for m, c in comparison.items():
        params = ", ".join(f"{k}={v}" for k, v in c["best_params"].items())
        lines.append(f"| {m} | {c['cv_auc_mean']:.3f} +/- {c['cv_auc_std']:.3f} | {params} |")
    return "\n".join(lines)


def disease_section(disease_dir: Path, rel_prefix: str) -> str:
    meta = json.loads((disease_dir / "metadata.json").read_text(encoding="utf-8"))
    comp = json.loads((disease_dir / "metrics.json").read_text(encoding="utf-8"))
    chosen = comp[meta["selected_model"]]["test_at_tuned"]
    d = disease_dir.name
    test_best = max(comp, key=lambda m: comp[m]["test_at_0.5"]["roc_auc"]["value"])
    test_note = ""
    if test_best != meta["selected_model"]:
        tb = comp[test_best]["test_at_0.5"]["roc_auc"]
        sel = comp[meta["selected_model"]]["test_at_0.5"]["roc_auc"]
        test_note = (
            f"\n\n{test_best} scores slightly higher ROC-AUC on the test set "
            f"({tb['value']:.3f} vs {sel['value']:.3f}), but the 95% intervals overlap almost "
            f"completely ([{tb['ci_low']:.2f}, {tb['ci_high']:.2f}] vs "
            f"[{sel['ci_low']:.2f}, {sel['ci_high']:.2f}]). The test set is used only to report, "
            "never to choose: picking the winner on the test set would make its score an "
            "optimistic, selection-biased estimate."
        )
    return f"""## {meta["display_name"]}

Train {meta["n_train"]} / test {meta["n_test"]} rows, positive rate {meta["positive_rate"]:.1%}.

### Cross-validation on the training set (model selection)
{cv_table(comp)}

### Held-out test set at default threshold 0.50 (value [95% bootstrap CI])
{metrics_table(comp, "test_at_0.5")}

### Held-out test set at tuned threshold {meta["threshold"]:.2f}
{metrics_table(comp, "test_at_tuned")}

**Selected model: {meta["selected_model"]}.** {meta["selection_reason"]}{test_note}

At the tuned threshold the selected model catches {chosen["recall"]["value"]:.0%} of positive
cases (recall) with precision {chosen["precision"]["value"]:.0%}. Threshold rule:
{meta["threshold_rule"]}.

| ROC | Calibration | Confusion matrix |
|---|---|---|
| ![roc]({rel_prefix}/{d}/roc.png) | ![cal]({rel_prefix}/{d}/calibration.png) | ![cm]({rel_prefix}/{d}/confusion.png) |
"""


def write_report() -> Path:
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    sections = [
        disease_section(p, "../models")
        for p in sorted(MODELS_DIR.iterdir())
        if (p / "metadata.json").exists()
    ]
    body = (
        "# ML model report\n\n_Generated by `python -m carepilot.ml.train`. Do not edit by hand._\n\n"
        "Confidence intervals: percentile bootstrap, 1000 resamples of the test set. "
        "Small test sets give wide intervals; differences between models whose intervals "
        "overlap heavily are not conclusive.\n\n" + "\n".join(sections)
    )
    out = REPORTS_DIR / "ml_report.md"
    out.write_text(body, encoding="utf-8")
    return out
